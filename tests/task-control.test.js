'use strict';
const assert = require('./lib/assertions')('task-control');
const { createControl } = require('../task-control');
const { createApprovals } = require('../approvals');
const { createController } = require('../desktop-automation');
const { createQueue } = require('../agent-jobs');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  const events = [], saved = [];
  const control = createControl({ save: s => saved.push(s), broadcast: e => events.push(e) });
  const tokens = createApprovals(); control.onStop(tokens.clear);
  const token = tokens.issue('fixture');
  const operation = control.operation();
  control.resume(); operation.check();
  assert.equal(saved.length, 0, 'resume is idempotent while already running');
  assert.equal(operation.signal.aborted, false);
  control.stop();
  assert.equal(operation.signal.aborted, true);
  assert.equal(tokens.consume(token, 'fixture'), false);
  assert.throws(() => control.operation(), /Emergency stop/);
  control.resume();
  assert.throws(operation.check, /invalidated/, 'resume never makes an old operation valid');
  operation.release();
  assert.deepEqual(saved, [true, false]);
  assert.equal(events[0].type, 'emergency-stop');
  const anotherApprovalStore = createApprovals(), anotherToken = anotherApprovalStore.issue('other-target');
  const thisToken = tokens.issue('this-target');
  require('../approvals').revokeAll();
  assert.equal(anotherApprovalStore.consume(anotherToken, 'other-target'), false, 'all standard tool approval stores are revoked');
  assert.equal(tokens.consume(thisToken, 'this-target'), false);
  const afterRestart = createControl({ stopped: true, initialEpoch: control.status().epoch });
  afterRestart.resume();
  assert.ok(afterRestart.status().epoch > control.status().epoch, 'the revision remains ordered across restart');
  let actions = 0;
  const desktop = createController({ control, adapter: async req => {
    if (req.operation === 'list') return { windows: [{ handle: '1', pid: 2, title: 'Fixture', app: 'Fixture' }] };
    if (req.operation === 'inspect') return { controls: [{ runtimeId: '1', name: 'Save', type: 'ControlType.Button', enabled: true, invoke: true }] };
    actions++; return {};
  } });
  const window = (await desktop.list()).windows[0];
  const snapshot = await desktop.inspect(window.id);
  const input = { snapshotId: snapshot.snapshotId, controlId: snapshot.controls[0].id, action: 'click' };
  const preview = await desktop.act(input);
  control.stop();
  assert.equal((await desktop.act({ ...input, approved: true, approvalToken: preview.body.approvalToken })).status, 409);
  control.resume();
  assert.equal((await desktop.act({ ...input, approved: true, approvalToken: preview.body.approvalToken })).status, 409);
  assert.equal(actions, 0, 'stopped desktop approvals cannot execute after resume');
  const { EventEmitter } = require('node:events');
  const killedChildren = [];
  const owned = require('../owned-processes').createRegistry({ control, kill: child => killedChildren.push(child.pid) });
  const live = new EventEmitter(); live.pid = 1234; live.exitCode = null;
  const exited = new EventEmitter(); exited.pid = 1235; exited.exitCode = 0;
  owned.track(live); owned.track(exited);
  control.stop();
  assert.deepEqual(killedChildren, [1234], 'stop targets only live registered children');
  live.emit('exit'); assert.equal(owned.size(), 1);
  control.resume();
  let spawned = 0, killed = 0, hotkeyStops = 0, helper;
  const hotkey = require('../emergency-hotkey').createHotkey({ supported: true, onStop: () => hotkeyStops++, spawn: () => {
    spawned++; helper = new EventEmitter(); helper.stdout = new EventEmitter(); helper.stderr = new EventEmitter();
    helper.kill = () => { killed++; }; return helper;
  } });
  assert.equal(spawned, 0, 'registration is opt-in');
  hotkey.set(true); helper.stdout.emit('data', Buffer.from('REA')); helper.stdout.emit('data', Buffer.from('DY\nSTOP\n'));
  assert.equal(hotkey.status().running, true);
  assert.equal(hotkeyStops, 1, 'only a ready helper STOP message triggers cancellation');
  hotkey.set(true); assert.equal(spawned, 1, 'enabling twice never creates a second helper');
  hotkey.set(false); helper.stdout.emit('data', Buffer.from('STOP\n'));
  assert.equal(hotkeyStops, 1, 'disabled helpers cannot trigger actions');
  assert.equal(killed, 1);
  const unsupported = require('../emergency-hotkey').createHotkey({ supported: false, onStop() {} });
  assert.throws(() => unsupported.set(true), /Windows/);
  let faultChildKilled = false;
  const faultChild = new EventEmitter(); faultChild.stdout = new EventEmitter(); faultChild.stderr = new EventEmitter();
  faultChild.kill = () => { faultChildKilled = true; };
  const faultHotkey = require('../emergency-hotkey').createHotkey({ supported: true, spawn: () => faultChild, onStop() {},
    save: on => { if (!on) throw new Error('fixture disk full'); } });
  faultHotkey.set(true);
  assert.throws(() => faultHotkey.set(false), /disk full/);
  assert.ok(faultChildKilled && !faultHotkey.status().running && !faultHotkey.status().enabled, 'write failure cannot keep a disabled registration alive');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'jarvis-control-'));
  try {
    let release, ran = 0;
    const registry = { validateStep: raw => ({ ok: true, step: { ...raw, tier: 'safe' } }) };
    const queue = createQueue({ file: path.join(tmp, 'jobs.json'), registry, control, executors: {
      read: async () => { ran++; await new Promise(resolve => { release = resolve; }); return 'fixture'; }
    } });
    const first = queue.submit({ steps: [{ tool: 'read', args: {} }] });
    const queued = queue.submit({ steps: [{ tool: 'read', args: {} }] });
    await tick();
    control.stop();
    assert.equal(queue.get(queued.id).status, 'cancelled');
    assert.throws(() => queue.submit({ steps: [{ tool: 'read', args: {} }] }), /Emergency stop/);
    release(); await tick(); await tick();
    assert.equal(queue.get(first.id).status, 'cancelled');
    assert.equal(queue.get(first.id).steps[0].output, undefined, 'discard in-flight result after cancellation');
    control.resume(); await tick();
    assert.equal(ran, 1, 'resume cannot revive cancelled queued work');
    assert.equal(queue.get(queued.id).status, 'cancelled');
    assert.report();
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
